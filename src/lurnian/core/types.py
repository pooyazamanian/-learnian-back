"""Column types, defaults and mixins shared by all model modules.

Two rules from the database design live here so they cannot be forgotten in a
model: identifiers are UUIDv7 generated in the application, and every timestamp
is ``TIMESTAMPTZ`` with the database clock as the source of truth.
"""

from __future__ import annotations

import uuid
from collections.abc import Callable
from datetime import datetime
from typing import Any, Final

from sqlalchemy import DateTime, func
from sqlalchemy.orm import Mapped, mapped_column


def new_uuid() -> uuid.UUID:
    """Return a time-ordered UUIDv7 generated in the application.

    Identifiers are never generated by the database (no ``DEFAULT uuidv7()``):
    a single generation point keeps the ordering guarantee testable.
    """
    return uuid.uuid7()


#: Type alias for a Python-side UUIDv7 default.
UUIDDefault: Final[Callable[[], uuid.UUID]] = new_uuid


class CreatedAtMixin:
    """Adds a non-null ``created_at`` stamped by the database clock."""

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )


class TimestampMixin(CreatedAtMixin):
    """Adds ``updated_at`` on top of :class:`CreatedAtMixin`."""

    updated_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
        onupdate=func.now(),
    )


def as_identity() -> Any:
    """Return a ``GENERATED BY DEFAULT AS IDENTITY`` clause."""
    from sqlalchemy import Identity

    return Identity(always=False)
